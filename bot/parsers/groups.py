"""Нормализация имён учебных групп.

Одно и то же имя группы в источниках пишется по-разному:

- DOCX расписания: «26 С1», «25 КАД», «026 С», «26МОСДР-1», «26ИМС1»;
- лист замен (HTML): «26КАД», «026 С», «25 КАД», «24ИМС-1».

Чтобы замены находили нужные пары расписания, обе стороны приводятся к
одному виду: верхний регистр, без пробелов и дефисов, ведущая «О»
заменяется на «0» (в некоторых источниках год группы пишут буквой).
"""
from __future__ import annotations

import re

# Пробелы и дефисы (включая неразрывный пробел) в имени группы не значимы.
_STRIP_RE = re.compile(r"[\s\u00a0\-]+")

# Ведущие «О»/«O» — это ноль: «О26КАД» и «O26KAД» → «026КАД».
_LEADING_LETTER_O = frozenset({"О", "O"})


def normalize_group_name(name: str) -> str:
    """Привести имя группы к каноническому виду.

    Args:
        name: имя группы как оно записано в источнике («26 С1», «О26КАД»).

    Returns:
        Верхний регистр, без пробелов и дефисов, с ведущим «0» вместо «О»:
        ``«26 С1» → «26С1»``, ``«О26КАД» → «026КАД»``,
        ``«26МОСДР-1» → «26МОСДР1»``. Пустая строка — пустая строка.
    """
    result = _STRIP_RE.sub("", name.strip().upper())
    if result and result[0] in _LEADING_LETTER_O:
        result = "0" + result[1:]
    return result