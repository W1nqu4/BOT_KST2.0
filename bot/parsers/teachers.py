def full_fio(name: str) -> str:
    """Вернуть полное ФИО по фамилии или фамилии с инициалами.

    Args:
        name: фамилия («Витюгова»), фамилия с инициалами («Мицкевич Т.И.»)
            либо произвольная строка («вакансия»).

    Returns:
        Полное ФИО из :data:`TEACHERS`; если совпадения нет — входная
        строка без изменений (с обрезкой пробелов).

    Побочный эффект: для записей с пометкой «(ФИО уточняется)» пишется
    WARNING — один раз на фамилию за сессию (решение владельца: помечать
    нужно только в самом справочнике, а не в БД, и не засорять лог).
    """
    key = name.strip()
    if not key:
        return key

    # Точное совпадение по фамилии.
    if key in TEACHERS:
        return _mark_placeholder(key, TEACHERS[key])

    # Фамилия + инициалы: «Мицкевич Т.И.» → «Мицкевич».
    # Граница — пробел, чтобы «Новикова» не совпала с «Новиков».
    for short, full in TEACHERS.items():
        if key.startswith(short + " "):
            return _mark_placeholder(short, full)

    # ё/е: «Лунёва» ↔ «Лунева».
    normalized = key.replace("ё", "е").replace("Ё", "Е")
    for short, full in TEACHERS.items():
        if short.replace("ё", "е") == normalized:
            return _mark_placeholder(short, full)

    return key


def _mark_placeholder(surname: str, value: str) -> str:
    """Вернуть значение ФИО; для незаполненных — один WARNING за сессию."""
    if PLACEHOLDER_MARK in value and surname not in _WARNED_PLACEHOLDERS:
        _WARNED_PLACEHOLDERS.add(surname)
        logger.warning(
            "teacher FIO not filled yet",
            extra={"surname": surname},
        )
    return value


def is_known_surname(name: str) -> bool:
    """Есть ли фамилия в справочнике (с учётом ё/е).

    Нужно парсерам, чтобы писать WARNING о неизвестных фамилиях с контекстом
    (группа, день, пара) — см. решение владельца проекта.
    """
    key = name.strip()
    if not key:
        return False
    if key in TEACHERS:
        return True
    normalized = key.replace("ё", "е").replace("Ё", "Е")
    return any(short.replace("ё", "е") == normalized for short in TEACHERS)
